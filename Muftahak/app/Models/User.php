class User extends Authenticatable
{
    /** @use HasFactory<\Database\Factories\UserFactory> */
    use HasFactory, Notifiable,HasApiTokens;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'firstName',
        'lastName',
        'birthday',
        'phoneNumber',
        'password',
        'personalIdImage',
        'personalImage'
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var list<string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            // 'email_verified_at' => 'datetime',
            // 'password' => 'hashed',
        ];
    }

    // public function username(){
    //     return 'phoneNumber';
    // }
     public function apartments()
    {
        return $this->belongsToMany(Apartment::class,'user_apartment');
    }
    public function favoriateApartments(){
        return $this->belongsToMany(Apartment::class,'favorites');
    }
    public function ratingApartments(){
        return $this->belongsToMany(Apartment::class,'rates');
    }
    public function notifications()
    {
        return $this->hasMany(Notification::class, 'user_id');
    }   
}
